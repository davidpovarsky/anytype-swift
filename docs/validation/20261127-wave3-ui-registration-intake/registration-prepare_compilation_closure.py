def identity(data):
    return {"blob": hashlib.sha1(b"blob " + str(len(data)).encode() + b"\0" + data).hexdigest(),
            "sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data)}


def emit(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n")


def methods(text):
    if "import XCTest" in text:
        return re.findall(r"\bfunc (test[A-Za-z0-9_]+)\(", text)
    # Swift Testing annotations in these exact files use one physical line;
    # a method may follow on that same line or the next one.
    found = re.findall(r"@Test[^\n]*?\bfunc (\w+)\(|@Test[^\n]*\n\s*func (\w+)\(", text)
    return [a or b for a, b in found]


