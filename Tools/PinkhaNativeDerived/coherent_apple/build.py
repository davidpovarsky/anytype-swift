#!/usr/bin/env python3
"""Build exact qualified139 source, plus a separately identified iOS fixture.

The production framework is built before fixture files exist. The second bind
reuses compilation caches but adds only explicitly tagged assertion/bridge
files. Neither old tests nor protobuf generation is repeated.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import platform
import plistlib
import re
import shutil
import signal
import subprocess
import sys

import contract
import fixture

sys.path.insert(0, str(contract.ROOT / "Tools/TorahNativeOperations"))
sys.path.insert(0, str(contract.ROOT / "Tools/PinkhaNativeDerived"))
from authorized_read import build_apple as binding
import coherent_read_runtime as composition
import run_account_lifecycle as processes


def prepare_variant_binding(prepared, bind_work, evidence, heart, kind):
    """Keep the generated scope beside its immutable dependency contract.

    The unchanged launcher requires that contract to be inside the temporary
    root's parent. Output frameworks and launcher receipts remain separate for
    each variant; only the reviewed dependency owner is shared.
    """
    contract.require(kind in ("production", "fixture"), "Unknown framework variant")
    temporary = bind_work / (kind + "-gomobile-tmp")
    audit = evidence / (kind + "-go-launcher")
    temporary.mkdir()
    audit.mkdir()
    env = dict(prepared["env"], TMPDIR=str(temporary), PINKHA_T5_MOBILE_TMP=str(temporary),
               PINKHA_T5_GO_AUDIT=str(audit))
    # Exercise the actual unchanged path/hash/native identity gate before
    # spending time in gomobile, and again inside every generated Go command.
    binding.launcher.load_seed_contract(Path(env["PINKHA_T5_GENERATED_CONTRACT"]),
        env["PINKHA_T5_GENERATED_CONTRACT_SHA256"], heart, temporary)
    contract.save(evidence / (kind + "-binding-scope.json"), dict(
        status="PASS_OWNED_BINDING_SCOPE", kind=kind, generated_temporary=str(temporary),
        contract_path=env["PINKHA_T5_GENERATED_CONTRACT"],
        contract_sha256=env["PINKHA_T5_GENERATED_CONTRACT_SHA256"], audit=str(audit)))
    return env, audit


def execute(args, receipt, run):
    control, heart, work = args.control, args.heart_source, args.work
    contract.require(platform.system() == "Darwin" and platform.machine() == "arm64", "Actual ARM64 Apple host required")
    contract.require(binding.git(control, "rev-parse", "HEAD") == args.expected_app_sha
                     and not binding.git(control, "status", "--porcelain"), "Exact clean controller required")
    contract.require(binding.git(heart, "rev-parse", "HEAD") == contract.HEART
                     and not binding.git(heart, "status", "--porcelain"), "Fresh exact native base required")
    contract.require(not work.exists() and not args.artifacts.exists(), "Fresh owned work/output required")
    contract.require(shutil.disk_usage(work.parent).free >= 12 * 1024**3, "Disk reserve below 12 GiB")
    qualified = contract.qualified_native(args.native_proof)
    source_evidence = args.evidence / "native-source"
    source_evidence.mkdir()
    shutil.copyfile(qualified["patch"], source_evidence / "native-heart-integration.patch")
    shutil.copyfile(args.native_proof / "runtime-source/native-heart-integration.json", source_evidence / "native-heart-integration.json")
    producer = json.loads(run(["gh", "api", "repos/davidpovarsky/anytype-swift/actions/runs/" + contract.NATIVE_RUN],
                              "original-native-run").read_bytes())
    contract.validate_native_run(producer)
    work.mkdir()
    args.artifacts.mkdir()
    # The exact original patch contains generated bytes and every native source
    # in the qualified closure. Applying it does not rerun generators or tests.
    run(["git", "apply", "--check", str(qualified["patch"])], "qualified-patch-check")
    run(["git", "apply", str(qualified["patch"])], "qualified-patch-apply")
    composition.verify_source(heart, qualified["inventory"], qualified["generation"]["module_sha256"])
    contract.save(args.evidence / "native-source-before.json", qualified["source_sha256"])
    real_go = Path(shutil.which("go") or "").resolve(strict=True)
    contract.require(subprocess.check_output([str(real_go), "version"], text=True).strip() == "go version go1.26.5 darwin/arm64",
                     "Pinned Go1.26.5 ARM64 compiler required")
    xcode = run(["xcodebuild", "-version"], "xcode-version").read_text().strip()
    sdk = run(["xcrun", "--sdk", "iphonesimulator", "--show-sdk-version"], "simulator-sdk").read_text().strip()
    contract.require(xcode.startswith("Xcode 27") and sdk.split(".")[0] == "27", "Xcode27/iOS27 SDK required")
    helper_path = control / "Tools/PinkhaNativeDerived/build_custom_heart.py"
    contract.require(contract.digest(helper_path) == binding.binding.HELPER_SHA, "Reviewed binary helper changed")
    helper = binding.pair_ci.load_module("coherent_apple_binary_helper", helper_path)
    dependencies = [helper.fetch_tantivy(heart, arch) for arch in ("darwin-arm64", "ios-arm64-sim")]
    bind_work = work / "binding"
    bind_work.mkdir()
    gowork = bind_work / "go.work"
    gowork.write_text("go 1.26.5\n\nuse " + str(heart) + "\n\nreplace " + binding.pair_ci.GENPROTO_PATH + " => "
                     + binding.pair_ci.GENPROTO_PATH + " " + binding.pair_ci.GENPROTO_VERSION + "\n", encoding="utf8")
    env = dict(os.environ, CGO_ENABLED="1", GOMAXPROCS="2", GOMEMLIMIT="4096MiB", GOTOOLCHAIN="local",
               GOWORK=str(gowork), GOFLAGS="-mod=readonly")
    # This key selects the retained original *module declaration* seed. Product
    # identity comes only from qualified139 source and is recorded separately.
    prepared = binding.prepare_binding(control, heart, bind_work, args.evidence, real_go, env, gowork, helper, run,
                                       binding.CANDIDATE)
    env = prepared["env"]
    shutil.copyfile(prepared["graph_contract_path"], args.evidence / "generated-bind-contract.json")
    contract.require(contract.digest(args.evidence / "generated-bind-contract.json") == prepared["graph_contract_sha"],
                     "Archived binding contract differs")
    _, fixture_hashes, bridge_sha = fixture.source_files(control, qualified["original_fixture_files"])
    receipt.update(native_run=contract.NATIVE_RUN, native_source=contract.NATIVE_SOURCE,
                   patch_sha256=contract.PATCH, inventory_sha256=contract.INVENTORY,
                   native_source_count=139, native_source_sha256=qualified["source_sha256"],
                   native_module_sha256=qualified["generation"]["module_sha256"],
                   old_tests_executed=0, protobuf_generation_executed=0, xcode=xcode, simulator_sdk=sdk,
                   runtime_version=qualified["version"], bridge_sha256=bridge_sha,
                   original_fixture_sha256=contract.ORIGINAL_FIXTURE,
                   original_fixture_source_sha256=qualified["original_fixture_files"],
                   fixture_source_sha256=fixture_hashes, native_dependencies=dependencies,
                   dependency_seed_original_candidate=binding.CANDIDATE, frameworks={})
    contract.save(args.evidence / "build.json", receipt)
    installed_fixture = None
    try:
        for kind in ("production", "fixture"):
            is_fixture = kind == "fixture"
            if is_fixture:
                installed_fixture, actual_bridge = fixture.materialize(control, heart, qualified["original_fixture_files"])
                contract.require(installed_fixture == fixture_hashes and actual_bridge == bridge_sha, "Fixture source changed")
            destination = work / kind
            destination.mkdir()
            framework = destination / "Lib.xcframework"
            bind_env, audit = prepare_variant_binding(prepared, bind_work, args.evidence, heart, kind)
            tags = "nogrpcserver gomobile nowatchdog nosigar nomutexdeadlockdetector timetzdata rasterizesvg"
            ldflags = "-X github.com/anyproto/anytype-heart/util/vcs.GitSummary=" + qualified["version"]
            ldflags += " -X github.com/anyproto/anytype-heart/util/vcs.GitCommit=" + contract.HEART
            if is_fixture:
                tags += " " + contract.FIXTURE_TAG
                ldflags += " -X github.com/anyproto/anytype-heart/clientlibrary/service.t5ACLFixtureSHA=" + contract.ORIGINAL_FIXTURE
                ldflags += " -X github.com/anyproto/anytype-heart/clientlibrary/service.coherentAppleBridgeSHA=" + bridge_sha
            receipt["phase"] = "BIND_" + kind.upper()
            run([str(heart / "deps/gomobile"), "bind", "-tags", tags, "-ldflags", ldflags,
                 "-target=iossimulator/arm64", "-iosversion=17.0", "-o", str(framework),
                 "github.com/anyproto/anytype-heart/clientlibrary/service", "github.com/anyproto/anytype-heart/core"],
                kind + "-gomobile-bind", bind_env, timeout=3600)
            scopes = binding.validate_generated_scopes(dict(prepared, audit=audit), heart)
            binary = framework / "ios-arm64-simulator/Lib.framework/Lib"
            contract.require(binary.is_file(), "Missing actual ARM64sim slice")
            raw_sha = contract.digest(binary)
            combined = destination / "Lib-with-tantivy.a"
            run(["xcrun", "libtool", "-static", "-o", str(combined), str(binary),
                 str(heart / "deps/libs/ios-arm64-sim/libtantivy_go.a")], kind + "-tantivy-repack", bind_env)
            shutil.copyfile(combined, binary)
            headers = "\n".join(path.read_text() for path in (framework / "ios-arm64-simulator/Lib.framework/Headers").glob("*.h"))
            contract.require("ServicePinkhaTorahAuthorizedOperationRead" in headers, "Generated T2 read entry missing")
            contract.require(("ServicePinkhaCoherentAppleAuthorityFixture" in headers) is is_fixture,
                             "Fixture entry must exist only in the explicitly tagged framework")
            slices = helper.verify_framework_slices(framework, qualified["version"])
            binding.validate_simulator_framework(plistlib.loads((framework / "Info.plist").read_bytes()), slices,
                                                 expected_version=qualified["version"])
            hashes = {p.relative_to(framework).as_posix(): contract.digest(p) for p in sorted(framework.rglob("*")) if p.is_file()}
            receipt["frameworks"][kind] = dict(fixture_compiled=is_fixture,
                fixture_tag=contract.FIXTURE_TAG if is_fixture else None,
                binary_sha256=contract.digest(binary), unmerged_go_archive_sha256=raw_sha,
                files_sha256=hashes, binary_slices=slices, generated_scopes=scopes)
            contract.require({name: contract.digest(heart / name) for name in qualified["source_sha256"]}
                             == qualified["source_sha256"], "Qualified production source changed")
            if is_fixture:
                contract.require({name: contract.digest(heart / "clientlibrary/service" / name) for name in installed_fixture}
                                 == installed_fixture, "Fixture source changed during bind")
            else:
                composition.verify_source(heart, qualified["inventory"], qualified["generation"]["module_sha256"])
            artifact = contract.FIXTURE_ARTIFACT if is_fixture else contract.PRODUCTION_ARTIFACT
            packaged = dict(status="PASS", build_status="APPLE_FRAMEWORK_BUILT_NOT_EXECUTED", target="ios",
                heart_sha=contract.HEART, patch_sha256=contract.PATCH, inventory_sha256=contract.INVENTORY,
                files=qualified["inventory"]["files"], marker="pinkha-native-derived-v1-" + contract.PATCH,
                capability_marker="pinkha-native-t5-lookup-v1-" + contract.PATCH,
                expected_app_get_version=qualified["version"], runtime_variant=contract.VARIANT,
                artifacts=[dict(path=name, sha256=sha) for name, sha in hashes.items()], binary_slices=slices,
                github_run_id=receipt["run_id"], github_run_attempt=receipt["run_attempt"], integration_sha=args.expected_app_sha,
                app_get_version_status="NOT_RUN_BUILD_ONLY", native_test_invocations=0, fixture_included=is_fixture,
                target_architecture="arm64", target_environment="simulator", native_source_run=contract.NATIVE_RUN,
                native_source_sha=contract.NATIVE_SOURCE, native_source_count=139, selected_framework=kind,
                fixture_tag=contract.FIXTURE_TAG if is_fixture else None,
                fixture_source_sha256=fixture_hashes if is_fixture else {},
                bridge_sha256=bridge_sha if is_fixture else None,
                product_acceptance="NOT_RUN", swift_pairing_status="NOT_RUN", client_enablement="DISABLED_PENDING_ACCEPTANCE")
            packaged_name = "PinkhaNativeHeartBuild.json" if not is_fixture else "CoherentHeartFixtureBuild.json"
            contract.save(destination / packaged_name, packaged)
            receipt_evidence = args.evidence / kind
            contract.save(receipt_evidence / "custom-heart-build.json", packaged)
            archive = args.artifacts / (artifact + ".tar.gz")
            run(["tar", "-czf", str(archive), "-C", str(destination), "Lib.xcframework", packaged_name],
                kind + "-archive", dict(bind_env, COPYFILE_DISABLE="1"))
            receipt["frameworks"][kind].update(artifact_name=artifact + ".tar.gz", artifact_sha256=contract.digest(archive))
            contract.save(receipt_evidence / "runtime-artifact.json", dict(status="APPLE_RUNTIME_ARTIFACT_BUILT_NOT_EXECUTED",
                path=archive.name, sha256=contract.digest(archive), receipt_sha256=contract.digest(destination / packaged_name),
                runtime_variant=contract.VARIANT, fixture_included=is_fixture, integration_sha=args.expected_app_sha,
                github_run_id=receipt["run_id"], github_run_attempt=receipt["run_attempt"],
                patch_sha256=contract.PATCH, inventory_sha256=contract.INVENTORY, heart_sha=contract.HEART))
            contract.save(args.evidence / "build.json", receipt)
    finally:
        if installed_fixture is not None:
            fixture.remove_owned(heart, installed_fixture)
        composition.verify_source(heart, qualified["inventory"], qualified["generation"]["module_sha256"])
        contract.save(args.evidence / "native-source-after.json", {name: contract.digest(heart / name) for name in qualified["source_sha256"]})
    contract.require(contract.qualified_native(args.native_proof)["source_sha256"] == qualified["source_sha256"], "Original proof changed")
    contract.require(binding.git(control, "rev-parse", "HEAD") == args.expected_app_sha
                     and not binding.git(control, "status", "--porcelain"), "Control source changed")
    receipt.update(status="BUILT_DISTINCT_COHERENT_APPLE_FRAMEWORKS_NOT_EXECUTED", phase="COMPLETE",
                   production_binary_execution="NOT_RUN", fixture_ios_execution="NOT_RUN")
    contract.validate_build_receipt(receipt, args.expected_app_sha, receipt["run_id"])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("control", "heart-source", "native-proof", "work", "evidence", "artifacts"):
        parser.add_argument("--" + name, type=Path, required=True)
    parser.add_argument("--expected-app-sha", required=True)
    args = parser.parse_args()
    for name in ("control", "heart_source", "native_proof", "work", "evidence", "artifacts"):
        setattr(args, name, getattr(args, name).resolve())
    args.evidence.mkdir(parents=True, exist_ok=True)
    path = args.evidence / "build.json"
    contract.require(not path.exists(), "Refuse existing build receipt")
    receipt = dict(status="NOT_RUN", phase="PREFLIGHT", app_sha=args.expected_app_sha,
                   run_id=os.environ.get("GITHUB_RUN_ID"), run_attempt=os.environ.get("GITHUB_RUN_ATTEMPT"),
                   commands=[], started_at=datetime.now(timezone.utc).isoformat())
    contract.require(re.fullmatch(r"[0-9a-f]{40}", args.expected_app_sha) and (receipt["run_id"] or "").isdigit()
                     and (receipt["run_attempt"] or "").isdigit(), "Exact real source/run required")
    previous = {number: signal.getsignal(number) for number in (signal.SIGTERM, signal.SIGINT)}
    cancelled = False
    def cancel(number, frame):
        nonlocal cancelled
        if not cancelled:
            cancelled = True
            raise KeyboardInterrupt(signal.Signals(number).name)
    for number in previous:
        signal.signal(number, cancel)
    def run(command, name, env=None, cwd=None, timeout=900):
        entry = dict(name=name, argv=list(map(str, command)), status="RUNNING")
        receipt["commands"].append(entry)
        contract.save(path, receipt)
        log = args.evidence / (name + ".log")
        try:
            entry["pid"] = processes.run_process(entry["argv"], cwd or args.heart_source, env or os.environ.copy(), log, timeout)
            entry["status"] = "PASS_EXIT_0"
        except BaseException as error:
            entry["status"] = "CANCELLED" if isinstance(error, KeyboardInterrupt) else "FAIL"
            raise
        finally:
            contract.save(path, receipt)
        return log
    try:
        execute(args, receipt, run)
    except BaseException as error:
        receipt.update(status="CANCELLED" if isinstance(error, KeyboardInterrupt) else "FAIL", error_type=type(error).__name__, error=str(error))
    finally:
        receipt["finished_at"] = datetime.now(timezone.utc).isoformat()
        contract.save(path, receipt)
        for number, handler in previous.items():
            signal.signal(number, handler)
    return int(receipt["status"] != "BUILT_DISTINCT_COHERENT_APPLE_FRAMEWORKS_NOT_EXECUTED")


if __name__ == "__main__":
    raise SystemExit(main())
