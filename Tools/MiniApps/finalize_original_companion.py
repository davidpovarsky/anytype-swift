#!/usr/bin/env python3
"""Finish original dependency preparation by restoring its exact qualified config.

The original Expo script appends build-search flags. Original producer04
explicitly required canonical Config03d instead. Preserve the generated bytes
and failed receipt, prove that exact append, and restore only this owned copy.
"""
from pathlib import Path
import argparse, ast, hashlib, json, os, platform, subprocess
from datetime import datetime, timezone

SOURCE = "86a6dde354947be9329fe1e8f4d45a433fe488c4"
CONFIG = "03d96d520f785e34d85b643e31bcb4a424e46e76a81c6b4c245f91eaac3e110f"
GENERATED = "d24ca1f0f9d77ea8e8db77ab303c6428d155aef7294eb4ad0f67ba7ee6449a2b"
HOST = "540507770659f00b8424b394c0c3857f52001cd13a0dc2bc3b38f313b385303a"
IDENTITY = "dca879b7fbbedf2f0243b7f3d90363ec5b6c468d82a49935de9219b1e38602a2"
DIFF = "863bf97e4b83fe9824be5345a7fcb2453f403a50d16ce3fdbc0c1c978b5482ab"
ORIGINAL_PRODUCER = "96a55cfe5556132fe9354f9c6dcc606fdeeae5817fa884a4bc6010b4e2759789"

def sha(raw):
    return hashlib.sha256(raw).hexdigest()

def digest(path):
    with Path(path).open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()

def require(value, reason):
    if not value:
        raise ValueError(reason)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--recovery-root", type=Path, required=True)
    args = parser.parse_args()
    root = args.recovery_root
    require(platform.system() == "Darwin" and platform.machine() == "arm64" and os.getuid() == 501,
            "Actual authorized Apple Silicon session required")
    require(root == Path("/Users/m1/development/anytype-root-active-20261125/miniapps-producer86-restore3")
            and root.resolve() == root, "Only the existing owned successful dependency workspace is admitted")
    source, evidence = root / "source", root / "preparation"
    controls = Path(__file__).resolve().parent
    result_path = evidence / "FINALIZATION.json"
    require(not result_path.exists(), "Preserve every original finalization receipt")
    result = {"status": "FAILED", "source": SOURCE, "appBuilds": 0, "testsExecuted": 0,
              "startedAt": datetime.now(timezone.utc).isoformat(),
              "helperSHA256": digest(__file__), "originalProducerSHA256": ORIGINAL_PRODUCER}
    try:
        prior_path = evidence / "RESULT.json"
        prior_raw = prior_path.read_bytes()
        prior = json.loads(prior_raw)
        require(prior["status"] == "FAILED" and prior["error"] ==
                {"type": "ValueError", "message": "Canonical configuration/runtime resource changed"},
                "Only the observed final configuration mismatch is admitted")
        require(prior["source"] == SOURCE and prior["appBuilds"] == prior["nativeTests"] == 0
                and prior["existingCheckoutUnchanged"] is True, "Original source or preparation scope differs")
        labels = ["clone-isolated-git", "checkout-original", "pin-original-diff-width",
                  "apply-exact-original-preparation", "install-nativescript", "prepare-nativescript",
                  "install-expo", "prepare-expo", "prepare-expo-types"]
        require([s["label"] for s in prior["steps"]] == labels, "All nine actual original commands required")
        for step in prior["steps"]:
            command = evidence / (step["label"] + ".command.json")
            log = evidence / (step["label"] + ".log")
            require(step["returncode"] == 0 and digest(command) == step["receiptSHA256"]
                    and digest(log) == step["logSHA256"], "Original command receipt/log changed or failed")
            receipt = json.loads(command.read_bytes())
            require(receipt["log_sha256"] == step["logSHA256"], "Original command output binding differs")
        identity_path, diff_path = controls / "source-identity.json", controls / "source-preparation.diff"
        require(digest(identity_path) == IDENTITY and digest(diff_path) == DIFF, "Exact original source evidence required")
        identity = json.loads(identity_path.read_bytes())
        files = identity["tracked_file_sha256"]
        require(identity["commit"] == SOURCE and len(files) == 7693, "Full original tracked source required")
        def verify():
            require(all((source / n).resolve().is_relative_to(source) and digest(source / n) == h
                        for n, h in files.items()), "Original tracked source changed")
            require(subprocess.check_output(["/usr/bin/git", "-C", str(source), "diff", "--binary", "HEAD"], timeout=20)
                    == diff_path.read_bytes(), "Original exact prepared diff changed")
            require(all(digest(source / p) == HOST for p in ["build/runtime-host/RuntimeHostResources.zip",
                    "AI_HLY/RuntimeHostResources.zip"]), "Original runtime resources changed")
        verify()
        require(subprocess.check_output(["/usr/bin/git", "-C", str(source), "rev-parse", "HEAD"], timeout=20).decode().strip()
                == SOURCE, "Original source commit changed")
        producer = Path("/Users/m1/builds/_preflight/native-86a6-controls-20261125/run-original-build-prefix04-recovery.py")
        require(digest(producer) == ORIGINAL_PRODUCER, "Original successful producer source differs")
        require('preparation["configuration_sha256"] == "' + CONFIG + '"' in producer.read_text(),
                "Original producer did not require this exact configuration")
        canonical_path = Path(prior["originalSource"]) / "Config.xcconfig"
        canonical, generated = canonical_path.read_bytes(), (source / "Config.xcconfig").read_bytes()
        require(sha(canonical) == CONFIG and sha(generated) == GENERATED, "Exact observed configurations required")
        generator_path = source / "Scripts/Expo/prepare-ios-dependencies.mjs"
        generator = generator_path.read_text()
        begin = generator.index("const expoXcconfigBlock = [")
        end = generator.index("].join('\\n');", begin) + len("].join('\\n');")
        block = generator[begin:end]
        node = "/Users/m1/builds/_preflight/native-owned-node245-20261125/node-v24.5.0-darwin-arm64/bin/node"
        script = "const repoRootPosix = process.argv[1];\n" + block + "\nprocess.stdout.write(expoXcconfigBlock);\n"
        suffix = subprocess.check_output([node, "-e", script, str(source)], timeout=20)
        require(generated == canonical + suffix, "Configuration difference is not the exact original Expo append")
        backup = evidence / "generated-expo-config-before-canonical-restoration.xcconfig"
        require(not backup.exists(), "Generated configuration backup already exists")
        backup.write_bytes(generated); os.chmod(backup, 0o600)
        (source / "Config.xcconfig").write_bytes(canonical)
        verify()
        require(digest(source / "Config.xcconfig") == CONFIG and canonical_path.read_bytes() == canonical
                and prior_path.read_bytes() == prior_raw, "Canonical configuration or original evidence changed")
        result.update(status="EXACT_SOURCE_AND_ORIGINAL_DEPENDENCIES_PREPARED_BUILD_NOT_RUN",
                      originalPreparationSHA256=sha(prior_raw), originalPreparationStatus="FAILED",
                      originalFailurePreserved=True, generatedConfigurationSHA256=GENERATED,
                      configurationSHA256=CONFIG, runtimeHostSHA256=HOST, trackedFilesVerified=7693,
                      originalIdentitySHA256=IDENTITY, originalDiffSHA256=DIFF,
                      exactExpoGeneratorSHA256=digest(generator_path), exactAppendedBlockSHA256=sha(suffix),
                      actualOriginalDependencyCommandsPassed=5, allOriginalCommandsPassed=9,
                      existingCheckoutUnchanged=True)
    except BaseException as error:
        result["error"] = {"type": type(error).__name__, "message": str(error)}
        raise
    finally:
        result["finishedAt"] = datetime.now(timezone.utc).isoformat()
        result_path.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
        os.chmod(result_path, 0o600)
        print(json.dumps({k: result[k] for k in ["status", "source", "appBuilds", "testsExecuted"]}), flush=True)

if __name__ == "__main__":
    main()
