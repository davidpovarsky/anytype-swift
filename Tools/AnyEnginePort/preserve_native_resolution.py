#!/usr/bin/env python3
"""Preserve and remove only Xcode's source-identical generated native lock."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess

import native_continuation_sources as sources

GENERATED = "NativeApp/AnyNative.xcodeproj/project.xcworkspace/xcshareddata/swiftpm/Package.resolved"
CANONICAL = "Modules/PinkhaAnyUI/Package.resolved"


def require(value, reason):
    if not value:
        raise ValueError(reason)


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def parse_lock(raw):
    def pairs(items):
        result = {}
        for key, value in items:
            require(key not in result, "duplicate_package_lock_key")
            result[key] = value
        return result
    value = json.loads(raw, object_pairs_hook=pairs)
    require(isinstance(value, dict) and set(value) == {"originHash", "pins", "version"}
            and type(value["version"]) is int and value["version"] == 3
            and isinstance(value["originHash"], str)
            and re.fullmatch(r"[0-9a-f]{64}", value["originHash"]),
            "package_lock_schema")
    require(isinstance(value["pins"], list) and value["pins"], "package_pins_missing")
    pins = {}
    for pin in value["pins"]:
        require(isinstance(pin, dict) and set(pin) == {"identity", "kind", "location", "state"}
                and isinstance(pin["identity"], str)
                and pin["identity"] not in pins, "duplicate_or_invalid_package_identity")
        pins[pin["identity"]] = pin
    return value, pins


def regular(path, root):
    require(path.resolve().is_relative_to(root.resolve()), "package_path_escaped_root")
    for part in (path, *path.parents):
        if part == root:
            break
        require(not part.is_symlink(), "package_path_symlink")
    require(path.is_file() and path.stat().st_size <= 65536, "regular_bounded_package_file")
    return path.read_bytes()


def preserve(root, evidence, derived):
    root = root.resolve()
    generated = root / GENERATED
    canonical = root / CANONICAL
    # The original source fence remains unchanged. Refuse every tracked change
    # and every other untracked source before touching the one generated output.
    protected = (*sources.PROTECTED, sources.PROVIDER, "Tools/AnyEnginePort",
                 ".github/workflows/pinkha-any-engine-port.yml")
    tracked = sources.git("diff", "--name-only", "-z", "HEAD", "--", *protected, root=root)
    unknown = sources.git("ls-files", "--others", "--exclude-standard", "-z",
                          "--", *protected, root=root).split(b"\0")
    require(not tracked and [x.decode() for x in unknown if x] == [GENERATED],
            "only_owned_generated_package_lock_may_be_dirty")
    expected = regular(canonical, root)
    require(expected == sources.git("show", "HEAD:" + CANONICAL, root=root),
            "canonical_package_lock_changed")
    actual = regular(generated, root)
    expected_value, expected_pins = parse_lock(expected)
    actual_value, actual_pins = parse_lock(actual)
    require(actual_pins == expected_pins, "generated_dependency_pins_changed")

    products = derived.resolve() / "Build/Products"
    require(products.is_relative_to(root / "build"), "products_outside_owned_build")
    manifests = sorted(products.glob("PinkhaAnyNativeApp_*.xctestrun"))
    require(len(manifests) == 1, "one_original_native_xctestrun_required")
    test_run = manifests[0]
    test_raw = regular(test_run, products)

    require(evidence.resolve().is_relative_to(root / "build") and not evidence.exists()
            and not evidence.is_symlink(), "new_owned_evidence_directory_required")
    evidence.mkdir(parents=True, exist_ok=False)
    (evidence / "generated-Package.resolved").write_bytes(actual)
    (evidence / "canonical-Package.resolved").write_bytes(expected)
    record = {
        "schemaVersion": 1, "status": "VERIFIED_GENERATED_LOCK_PRESERVED",
        "commit": sources.git("rev-parse", "HEAD", root=root).decode().strip(),
        "generatedPath": GENERATED, "generatedSHA256": digest(actual),
        "generatedBytes": len(actual), "generatedOriginHash": actual_value["originHash"],
        "canonicalPath": CANONICAL, "canonicalSHA256": digest(expected),
        "canonicalOriginHash": expected_value["originHash"],
        "pins": [actual_pins[name] for name in sorted(actual_pins)],
        "xctestrun": str(test_run), "xctestrunSHA256": digest(test_raw),
        "testsExecuted": 0, "buildProductsAccepted": False,
        "claimBoundary": "Exact published dependency pins; original generated bytes retained. "
                         "The existing clean-source and compiled-product admission gates still apply."
    }
    with (evidence / "receipt.json").open("x", encoding="utf-8") as stream:
        json.dump(record, stream, indent=2, sort_keys=True)
        stream.write("\n")
    require((evidence / "generated-Package.resolved").read_bytes() == actual
            and regular(generated, root) == actual, "generated_lock_changed_during_preservation")
    generated.unlink()
    sources.verify_worktree(root)
    return record


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--evidence", type=Path, required=True)
    parser.add_argument("--derived", type=Path, required=True)
    args = parser.parse_args()
    record = preserve(args.root, args.evidence, args.derived)
    if os.environ.get("GITHUB_ENV"):
        with open(os.environ["GITHUB_ENV"], "a", encoding="utf-8") as stream:
            stream.write("ANY_NATIVE_XCTESTRUN=" + record["xctestrun"] + "\n")
    print(json.dumps({key: record[key] for key in
                      ("status", "generatedSHA256", "canonicalSHA256", "testsExecuted")}))


if __name__ == "__main__":
    main()
